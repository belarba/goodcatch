// Copies art/*/*.png into index.html between // @art-start and // @art-end as data URLs, so the page stays one offline
// file. Also derives what the page needs and nobody draws: the greyed star and the dark silhouettes of unseen fish.
// Run `node tools/art-embed.mjs` after any change in art/; pista-check fails while the embedded copy is stale.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { decodePNG, encodePNG } from './png.mjs';

const root = new URL('../', import.meta.url), GROUPS = ['fish', 'portrait', 'plate', 'guests', 'ui'];
const url = buf => `data:image/png;base64,${buf.toString('base64')}`;
const recolour = (buf, fn) => { const { w, h, rgba } = decodePNG(buf); for (let i = 0; i < rgba.length; i += 4) if (rgba[i + 3]) rgba.set(fn(rgba[i], rgba[i + 1], rgba[i + 2]), i); return encodePNG(w, h, rgba); };

export function artBlock() {
  const art = {}, dim = {};
  for (const g of GROUPS) {
    const dir = new URL(`art/${g}/`, root);
    if (!existsSync(dir)) continue;
    for (const f of readdirSync(dir).filter(f => f.endsWith('.png')).sort()) {
      const buf = readFileSync(new URL(f, dir)), key = `${g}/${f.slice(0, -4)}`;
      const { w, h } = decodePNG(buf);
      art[key] = url(buf); dim[key] = [w, h];
      if (g === 'fish' || g === 'portrait') { art[`${key}:dark`] = url(recolour(buf, () => [0x1E, 0x4A, 0x5A])); dim[`${key}:dark`] = [w, h]; }
      if (key === 'ui/star') dim['ui/starOff'] = [w, h];
      if (key === 'ui/star') art['ui/starOff'] = url(recolour(buf, (r, g2, b) => { const y = (r * .3 + g2 * .59 + b * .11) * .55 + 70; return [y + 8, y + 2, y - 14]; }));
    }
  }
  return `// @art-start\n// Generated by tools/art-embed.mjs from art/. Do not edit.\nconst ART=${JSON.stringify(art)};\nconst ART_DIM=${JSON.stringify(dim)};\n// @art-end`;
}

// The descent's own pieces (art/descida/) go into descida/index.html, so the Pista page does not carry them.
export function descidaBlock() {
  const art = {}, dim = {}, dir = new URL('art/descida/', root);
  if (existsSync(dir)) for (const f of readdirSync(dir).filter(f => f.endsWith('.png')).sort()) {
    const buf = readFileSync(new URL(f, dir)), { w, h } = decodePNG(buf);
    art[f.slice(0, -4)] = url(buf); dim[f.slice(0, -4)] = [w, h];
  }
  return `// @art-descida-start\n// Generated by tools/art-embed.mjs from art/descida/. Do not edit.\nconst DART=${JSON.stringify(art)};\nconst DART_DIM=${JSON.stringify(dim)};\n// @art-descida-end`;
}

function embed(path, start, end, block) {
  const file = new URL(path, root), html = readFileSync(file, 'utf8');
  const a = html.indexOf(start), b = html.indexOf(end);
  if (a < 0 || b < a) throw new Error(`${start} markers not found in ${path}`);
  writeFileSync(file, html.slice(0, a) + block + html.slice(b + end.length));
  console.log(`${path}: ${(block.match(/":"data:image/g) || []).length} images, ${Math.round(block.length / 1024)} KB`);
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  embed('index.html', '// @art-start', '// @art-end', artBlock());
  embed('descida/index.html', '// @art-descida-start', '// @art-descida-end', descidaBlock());
}
